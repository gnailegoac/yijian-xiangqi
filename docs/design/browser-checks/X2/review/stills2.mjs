import { boardShot, sleep, ev } from './rlib.mjs';
export default async ({ page }) => {
  await sleep(page, 300);
  await boardShot(page, 'start');
  await ev(page, () => window.demo.arrowKinds());
  await sleep(page, 800);
  await ev(page, () => window.view.showArrows([{ from: { row: window.lab.state.bottom === 'red' ? 7 : 2, col: window.lab.state.bottom === 'red' ? 7 : 1 }, to: { row: window.lab.state.bottom === 'red' ? 7 : 2, col: 4 }, style: 'hint', demo: true }], { group: 'hint' }));
  await sleep(page, 900);
  await boardShot(page, 'arrows');
  await ev(page, () => { window.view.clearArrows(); return window.demo.arrowCannon(); });
  await sleep(page, 700);
  await ev(page, () => window.demo.arrowHorse());
  await sleep(page, 700);
  await boardShot(page, 'arrows2');
  await ev(page, () => { window.view.clearArrows(); return window.demo.hlPieces(); });
  await sleep(page, 700);
  await boardShot(page, 'hl');
  await ev(page, () => window.demo.hlArea());
  await sleep(page, 700);
  await boardShot(page, 'hlarea');
  await ev(page, () => window.demo.hlPlain());
  await sleep(page, 700);
  await boardShot(page, 'hlplain');
  await ev(page, () => { window.demo.hlOff(); window.demo.preview(); });
  await sleep(page, 2300);
  await boardShot(page, 'preview');
  await sleep(page, 1500);
  await ev(page, () => { window.demo.previewTrial(); });
  await sleep(page, 2300);
  await boardShot(page, 'previewT');
  await sleep(page, 1800);
  await ev(page, () => { window.demo.mated(); });
  await sleep(page, 2000);
  await boardShot(page, 'mated');
  await ev(page, () => { window.demo.select(); });
  await sleep(page, 600);
  await boardShot(page, 'select');
};
