// The whole script, compressed, with a shot at every station. Used at every size, theme and motion setting.
export default async ({ page, shot }) => {
  const w = (ms) => page.waitForTimeout(ms);
  const D = (fn, arg) => page.evaluate(fn, arg);
  const only = (process.env.ONLY ?? '').split(',').filter(Boolean);
  const S = async (name) => { if (!only.length || only.some((o) => name.includes(o))) await shot(name); };
  await S('00-start');
  await page.click('[data-choice="new"]');
  await w(1100); await S('01-deal');
  await w(5200);
  await D(() => window.__dev.act.move(7, 7, 7, 4));
  await w(2600); await S('02-trial-comment');
  await D(() => window.__dev.act.retract());
  await w(700); await S('03-retract');
  await D(() => window.__dev.act.tap(7, 4));
  await w(800);
  await D(() => window.__dev.act.confirm());
  await w(600); await S('04-stamp');
  await D(() => window.__dev.turnDone());
  await w(2600); await S('05-rival-caption-line');
  await D(() => window.__dev.act.move(7, 4, 3, 4));
  await w(1700); await S('06-held');
  await D(() => window.__dev.act.ask('show'));
  await w(1500); await S('07-show');
  await w(1800);
  await D(() => window.__dev.act.chip('seen'));
  await w(2400);
  await D(() => window.__dev.act.hint());
  await w(1900); await S('08-pouch1');
  await D(() => window.__dev.act.hint());
  await w(900); await S('09-pouch2');
  await w(1500);
  await D(() => window.__dev.act.hint());
  await w(2000); await S('10-pouch3');
  await D(() => window.__dev.act.chip('try'));
  await w(1200);
  await D(() => window.__dev.act.ask('reply'));
  await w(600); await S('11-ask-tool');
  await w(3600); await S('12-ask-answer');
  await D(() => window.__dev.act.confirm());
  await D(() => window.__dev.turnDone());
  await w(1300);
  await D(() => window.__dev.act.move(7, 1, 0, 1));
  await w(2500); await S('13-aim');
  await D(() => window.__dev.act.confirm());
  await w(1000); await S('14-capture-praise');
  await D(() => window.__dev.turnDone());
  await w(2600); await S('15-rival-threat');
  await D(() => window.__dev.act.undo());
  await w(1500); await S('16-undo');
  await D(() => window.__dev.startScene('fork'));
  await w(2200);
  await D(() => window.__dev.act.move(4, 2, 2, 3));
  await w(2200);
  await D(() => window.__dev.act.confirm());
  await w(700); await S('17-check-banner');
  await w(1100); await S('18-find-stamp');
  await w(1300); await S('19-find-lord');
  await D(() => window.__dev.turnDone());
  await w(1200);
  await D(() => window.__dev.act.move(2, 3, 3, 1));
  await w(1500);
  await D(() => window.__dev.act.confirm());
  await D(() => window.__dev.turnDone());
  await w(400); await S('20-in-check');
  await w(2400);
  // the conversation sheet
  await page.click('#history-button', { force: true }).catch(async () => { await page.click('.bubble'); });
  await w(700); await S('21-sheet');
  await D(() => document.querySelector('.chat__head')?.click());
  await w(500);
  await D(() => window.__dev.startScene('mate'));
  await w(2200);
  await D(() => window.__dev.act.move(7, 1, 7, 4));
  await w(2200);
  await D(() => window.__dev.act.confirm());
  await w(900); await S('22-mate-banner');
  await w(3600); await S('23-win-confetti');
  await w(2600); await S('24-proud-replay');
  await D(() => window.__dev.cardUp());
  await w(5200); await S('25-win-card');
  await D(() => window.__dev.startScene('loss'));
  await w(2200);
  await D(() => window.__dev.act.move(6, 8, 5, 8));
  await w(1300);
  await D(() => window.__dev.act.confirm());
  await w(2600); await S('26-loss-banner');
  await D(() => window.__dev.cardUp());
  await w(4200); await S('27-loss-card');
  const state = await D(() => ({ phase: document.querySelector('#app').dataset.phase, layout: document.querySelector('#app').dataset.layout,
    motion: document.documentElement.dataset.motion, theme: document.documentElement.dataset.theme,
    scroll: [document.documentElement.scrollWidth - innerWidth, document.documentElement.scrollHeight - innerHeight] }));
  console.error('tour', JSON.stringify(state));
};
