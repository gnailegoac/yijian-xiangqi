/**
 * Compact mailbox position shared by search and facts (contract section 4.4; complete specification in Appendix A2).
 *
 * Representation (A2.1): `squares` is a 16x16 mailbox, sq = ((row + 3) << 4) | (col + 3), so the board occupies ranks 3..12 and
 * files 3..11 and every off-board step lands on a 0 cell of IN_BOARD. Piece code = side tag (8 red, 16 black) + type; 0 = empty.
 * A move is the integer from | (to << 8); 0 is "no move". Side to move: 0 red, 1 black.
 * Rows 0..4 are squares < 0x80, rows 5..9 are squares >= 0x80.
 */

import { PIECE_VALUE, CROSSED_PAWN_VALUE } from './codes.js';

/** @import { Board, Color, MoveRef, PieceType } from './types.js' */

export const RED = 0, BLACK = 1;
export const KING = 0, ADVISOR = 1, ELEPHANT = 2, HORSE = 3, ROOK = 4, CANNON = 5, PAWN = 6;
/** Indexed by piece type code. @type {PieceType[]} */
export const TYPE_NAME = ['king', 'advisor', 'elephant', 'horse', 'rook', 'cannon', 'pawn'];

/** @param {number} row @param {number} col @returns {number} square index */
export const sqOf = (row, col) => ((row + 3) << 4) | (col + 3);
/** @param {number} sq @returns {number} row 0..9 */
export const rowOf = sq => (sq >> 4) - 3;
/** @param {number} sq @returns {number} col 0..8 */
export const colOf = sq => (sq & 15) - 3;
/** @param {number} from @param {number} to @returns {number} move integer */
export const mkMove = (from, to) => from | (to << 8);
/** @param {number} mv @returns {number} origin square */
export const mvFrom = mv => mv & 255;
/** @param {number} mv @returns {number} destination square */
export const mvTo = mv => (mv >> 8) & 255;

// ---- lookup tables (A2.1) ----

/** 1 on the 90 board squares. */
const IN_BOARD = new Uint8Array(256);
/** 1 on the 18 squares of the two palaces. */
const IN_FORT = new Uint8Array(256);
for (let row = 0; row < 10; row++) {
  for (let col = 0; col < 9; col++) {
    IN_BOARD[sqOf(row, col)] = 1;
    if (col >= 3 && col <= 5 && (row <= 2 || row >= 7)) IN_FORT[sqOf(row, col)] = 1;
  }
}

const ORTHO = [-16, -1, 1, 16];
const DIAG = [-17, -15, 15, 17];
/** Horse jumps, two per leg; the leg of HORSE_JUMP[2 * i] and HORSE_JUMP[2 * i + 1] is ORTHO[i]. */
const HORSE_JUMP = [-33, -31, -18, 14, -14, 18, 31, 33];
/** Reverse horse squares (who attacks me), two per diagonal leg; the leg of HORSE_FROM[2 * i] and [2 * i + 1] is DIAG[i]. */
const HORSE_FROM = [-33, -18, -31, -14, 14, 31, 18, 33];

/** Capacity of the undo stacks in plies. */
const STACK_SIZE = 1024;
/** At most this many game positions are loaded by seedHistory (the newest ones); the rest of the stack stays free for the search. */
const MAX_SEED = STACK_SIZE - 256;
/** The dummy move of a seeded history entry: non-zero, so repetition scans walk through it. */
const SEED_MOVE = 0xffff;
/** Piece-list slots per side: one per board square, so that any placement fits. */
const PIECE_SLOTS = 90;
/** Size (a power of two) of the counting filter over the keys on the undo stacks. */
const REP_FILTER_SIZE = 4096;

// ---- piece-square tables (A2.3), generated by formula; index (pieceCode << 8) | sq, material included ----

const PST = new Int16Array(23 * 256);
for (let row = 0; row < 10; row++) {
  for (let col = 0; col < 9; col++) {
    const adv = 9 - row;                    // ranks advanced, 0..9 (red point of view)
    const cen = 4 - Math.abs(4 - col);      // 0..4
    const edge = col === 0 || col === 8;
    const table = [0, 0, 0, 0, 0, 0, 0];
    table[KING] = row === 9 ? (col === 4 ? 10 : 4) : row === 8 ? -8 : -20;
    table[ADVISOR] = 200 + (row === 8 && col === 4 ? 6 : 0);
    table[ELEPHANT] = 200 + (row === 7 && col === 4 ? 8 : edge ? -6 : 0);
    table[HORSE] = 400 + cen * 8 + Math.min(adv, 7) * 6 - (edge ? 16 : 0) - (adv === 0 ? 14 : 0)
      - (row === 8 && col === 4 ? 40 : 0)
      + (adv >= 6 && adv <= 8 && col >= 2 && col <= 6 ? 16 : 0);
    table[ROOK] = 900 + cen * 3 + adv * 2 - (adv === 0 ? 10 : 0) + (adv >= 4 && adv <= 8 ? 10 : 0);
    table[CANNON] = 450 + (col === 4 && adv >= 2 && adv <= 4 ? 18 : cen * 3) + (adv === 9 && (col <= 1 || col >= 7) ? 12 : 0)
      + Math.min(adv, 5) * 2;
    table[PAWN] = 100 + (adv >= 3 && col === 4 ? 6 : 0)
      + (adv >= 5 ? 70 + cen * 8 + (adv - 5) * 10 : 0) + (adv >= 7 && col >= 2 && col <= 6 ? 30 : 0) - (adv === 9 ? 80 : 0);
    for (let type = KING; type <= PAWN; type++) {
      PST[((8 + type) << 8) | sqOf(row, col)] = table[type];          // red
      PST[((16 + type) << 8) | sqOf(9 - row, col)] = table[type];     // black: the vertically mirrored square
    }
  }
}

// ---- Zobrist hashing (A2.1): two independent 32-bit streams from a fixed-seed xorshift32 ----

/** @param {number} seed @returns {() => number} signed 32-bit values */
function xorshift32(seed) {
  let s = seed >>> 0;
  return () => {
    s ^= s << 13; s >>>= 0;
    s ^= s >>> 17;
    s ^= s << 5; s >>>= 0;
    return s | 0;
  };
}
const Z_KEY = new Int32Array(14 * 256), Z_LOCK = new Int32Array(14 * 256);
const nextKey = xorshift32(0x9E3779B9), nextLock = xorshift32(0x7F4A7C15);
for (let i = 0; i < 14 * 256; i++) {
  Z_KEY[i] = nextKey();
  Z_LOCK[i] = nextLock();
}
/** One extra value from each stream for "black to move". */
const Z_SIDE_KEY = nextKey(), Z_SIDE_LOCK = nextLock();
/** Z_BASE[pieceCode] = offset of that piece's 256 entries in Z_KEY / Z_LOCK (red 0..6, black 7..13). */
const Z_BASE = new Int32Array(24);
for (let type = KING; type <= PAWN; type++) {
  Z_BASE[8 + type] = type << 8;
  Z_BASE[16 + type] = (7 + type) << 8;
}

// ---- material for static exchange evaluation (A2.4) and FEN letters ----

/** Indexed by piece type; a pawn across the river counts CROSSED_PAWN_VALUE. */
const SEE_VALUE = TYPE_NAME.map(name => PIECE_VALUE[name]);

/** @param {number} pc piece code (not 0) @param {number} sq the square it stands on @returns {number} */
function materialOf(pc, sq) {
  if ((pc & 7) !== PAWN) return SEE_VALUE[pc & 7];
  return (pc < 16 ? sq < 0x80 : sq >= 0x80) ? CROSSED_PAWN_VALUE : SEE_VALUE[PAWN];
}

/** FEN letter of a red piece, indexed by type. */
const FEN_LETTER = 'KABNRCP';
/** Input letters (upper case) to piece type; E and H are accepted for elephant and horse. @type {Record<string, number>} */
const FEN_TYPE = { K: KING, A: ADVISOR, B: ELEPHANT, E: ELEPHANT, N: HORSE, H: HORSE, R: ROOK, C: CANNON, P: PAWN };

export class Position {
  /** Side to move: RED or BLACK. Read-only for callers. @type {number} */
  side;
  /** The 16x16 mailbox of piece codes. @readonly @type {Uint8Array} */
  squares;
  /** 32-bit Zobrist hash of the position. Read-only for callers. @type {number} */
  key;
  /** Second, independent 32-bit Zobrist hash (verification). Read-only for callers. @type {number} */
  lock;
  /** kingSq[side] = square of that side's king. Read-only for callers. @readonly @type {Int32Array} */
  kingSq;
  /** count[side][type] = number of pieces. Read-only for callers. @readonly @type {Int32Array[]} */
  count;
  /** vl[side] = material + piece-square sum of that side (A2.1). Internal; only position.test.js may read it. @readonly @type {Int32Array} */
  vl;
  /** Undo stack: the move of each ply (0 = null move). Internal. @readonly @type {Uint16Array} */
  mvList;
  /** Undo stack: the captured piece code (0 = none). Internal. @readonly @type {Uint8Array} */
  pcList;
  /** Undo stack: the key before the move. Internal. @readonly @type {Int32Array} */
  keyList;
  /** Undo stack: 1 if the move gave check. Internal. @readonly @type {Uint8Array} */
  chkList;
  /** Height of the undo stacks. Internal. @type {number} */
  top;
  /** Number of entries loaded by seedHistory (they sit at the bottom of the stacks). Internal. @type {number} */
  seeded;
  /**
   * Stack index of the earlier occurrence that the last non-zero repStatus() found; an index below `seeded` is a
   * position of the game history, any other one lies on the path played with make(). Internal (search.js reads it).
   * @type {number}
   */
  repAt;
  /** Squares of the pieces of each side: red in slots [0, pieceN[0]), black in [90, 90 + pieceN[1]), in no particular order. Internal. @readonly @type {Uint8Array} */
  pieceSq;
  /** pieceN[side] = number of pieces of that side in pieceSq. Internal. @readonly @type {Int32Array} */
  pieceN;
  /** slotOf[sq] = index in pieceSq of the piece on sq (meaningful for occupied squares only). Internal. @readonly @type {Uint8Array} */
  slotOf;
  /** Undo stack: the pieceSq slot the captured piece had. Internal. @readonly @type {Uint8Array} */
  slList;
  /** Counting filter over keyList[0..top): repStatus skips its walk when the current key is not on the stack. Internal. @readonly @type {Uint16Array} */
  repFilter;

  /** An empty board with red to move. Positions are created with fromFen / fromBoard. */
  constructor() {
    this.side = RED;
    this.squares = new Uint8Array(256);
    this.key = 0;
    this.lock = 0;
    this.kingSq = new Int32Array(2);
    this.count = [new Int32Array(7), new Int32Array(7)];
    this.vl = new Int32Array(2);
    this.mvList = new Uint16Array(STACK_SIZE);
    this.pcList = new Uint8Array(STACK_SIZE);
    this.keyList = new Int32Array(STACK_SIZE);
    this.chkList = new Uint8Array(STACK_SIZE);
    this.top = 0;
    this.seeded = 0;
    this.repAt = 0;
    this.repFilter = new Uint16Array(REP_FILTER_SIZE);
    this.pieceSq = new Uint8Array(2 * PIECE_SLOTS);
    this.pieceN = new Int32Array(2);
    this.slotOf = new Uint8Array(256);
    this.slList = new Uint8Array(STACK_SIZE);
  }

  /** @param {string} fen  placement + side; extra fields ignored. @returns {Position} @throws {RangeError} */
  static fromFen(fen) {
    if (typeof fen !== 'string') throw new RangeError('FEN must be a string');
    const fields = fen.trim().split(/\s+/);
    const rows = fields[0].split('/');
    if (rows.length !== 10) throw new RangeError(`FEN needs 10 rows: ${fen}`);
    const p = new Position();
    for (let row = 0; row < 10; row++) {
      let col = 0;
      for (const ch of rows[row]) {
        if (ch >= '1' && ch <= '9') {
          col += ch.charCodeAt(0) - 48;
          continue;
        }
        const upper = ch.toUpperCase();
        const type = Object.hasOwn(FEN_TYPE, upper) ? FEN_TYPE[upper] : -1;
        if (type < 0) throw new RangeError(`FEN has an unknown letter "${ch}": ${fen}`);
        if (col > 8) throw new RangeError(`FEN row ${row} is longer than 9: ${fen}`);
        p.addPiece(sqOf(row, col), (ch === upper ? 8 : 16) + type);
        col++;
      }
      if (col !== 9) throw new RangeError(`FEN row ${row} does not sum to 9: ${fen}`);
    }
    if (p.count[RED][KING] !== 1 || p.count[BLACK][KING] !== 1) throw new RangeError(`FEN needs exactly one king per side: ${fen}`);
    const sideLetter = fields[1];
    if (sideLetter === 'b') p.changeSide();
    else if (sideLetter !== 'w' && sideLetter !== 'r') throw new RangeError(`FEN has an unknown side letter: ${fen}`);
    return p;
  }

  /** @param {Board} board @param {Color} turn @returns {Position} @throws {RangeError} */
  static fromBoard(board, turn) {
    const p = new Position();
    for (let row = 0; row < 10; row++) {
      for (let col = 0; col < 9; col++) {
        const piece = board[row][col];
        if (!piece) continue;
        const type = TYPE_NAME.indexOf(piece.type);
        if (type < 0 || (piece.color !== 'red' && piece.color !== 'black')) throw new RangeError('board has an unknown piece');
        p.addPiece(sqOf(row, col), (piece.color === 'red' ? 8 : 16) + type);
      }
    }
    if (p.count[RED][KING] !== 1 || p.count[BLACK][KING] !== 1) throw new RangeError('board needs exactly one king per side');
    if (turn === 'black') p.changeSide();
    else if (turn !== 'red') throw new RangeError('unknown side to move');
    return p;
  }

  /** @returns {string} "placement w|b" */
  toFen() {
    const b = this.squares;
    let out = '';
    for (let row = 0; row < 10; row++) {
      let empty = 0;
      for (let col = 0; col < 9; col++) {
        const pc = b[sqOf(row, col)];
        if (pc === 0) {
          empty++;
          continue;
        }
        if (empty > 0) {
          out += empty;
          empty = 0;
        }
        const letter = FEN_LETTER[pc & 7];
        out += pc < 16 ? letter : letter.toLowerCase();
      }
      if (empty > 0) out += empty;
      if (row < 9) out += '/';
    }
    return `${out} ${this.side === RED ? 'w' : 'b'}`;
  }

  /**
   * Load the reversible tail of the real game into the undo stacks so that repStatus sees cycles through game positions (A2.5).
   * Call it on a position on which no move has been made; a second call replaces the first.
   * @param {string[]} fens earlier positions since the last capture, oldest first (the current position excluded)
   * @returns {void}
   * @throws {RangeError} when a FEN is malformed
   */
  seedHistory(fens) {
    if (this.top !== this.seeded) throw new Error('seedHistory needs a position with no move made');
    const list = fens.length > MAX_SEED ? fens.slice(fens.length - MAX_SEED) : fens;
    const earlier = list.map(fen => Position.fromFen(fen));
    for (let i = 0; i < this.top; i++) this.repFilter[this.keyList[i] & (REP_FILTER_SIZE - 1)]--;
    const n = earlier.length;
    for (let i = 0; i < n; i++) {
      const next = i + 1 < n ? earlier[i + 1] : this;
      this.mvList[i] = SEED_MOVE;
      this.pcList[i] = 0;
      this.keyList[i] = earlier[i].key;
      this.chkList[i] = next.attacked(next.kingSq[next.side], next.side ^ 1) ? 1 : 0;
      this.repFilter[earlier[i].key & (REP_FILTER_SIZE - 1)]++;
    }
    this.top = n;
    this.seeded = n;
  }

  /**
   * Write the pseudo-legal moves of the side to move into a caller-supplied Int32Array(128) (A2.2).
   * The flying-general capture is not generated; facing kings are handled by the attack test.
   * @param {Int32Array} out
   * @param {boolean} capturesOnly
   * @returns {number} count
   */
  generate(out, capturesOnly) {
    const b = this.squares, side = this.side;
    const self = 8 << side, opp = 24 - self;
    // The pieces of the side to move, in piece-list order.
    const list = this.pieceSq, first = side * PIECE_SLOTS, end = first + this.pieceN[side];
    let n = 0;
    for (let slot = first; slot < end; slot++) {
      const from = list[slot];
      switch (b[from] & 7) {
        case KING:
          for (let i = 0; i < 4; i++) {
            const to = from + ORTHO[i];
            if (IN_FORT[to] === 0) continue;
            const target = b[to];
            if (capturesOnly ? (target & opp) !== 0 : (target & self) === 0) out[n++] = from | (to << 8);
          }
          break;
        case ADVISOR:
          for (let i = 0; i < 4; i++) {
            const to = from + DIAG[i];
            if (IN_FORT[to] === 0) continue;
            const target = b[to];
            if (capturesOnly ? (target & opp) !== 0 : (target & self) === 0) out[n++] = from | (to << 8);
          }
          break;
        case ELEPHANT:
          for (let i = 0; i < 4; i++) {
            const eye = from + DIAG[i];
            if (IN_BOARD[eye] === 0 || b[eye] !== 0) continue;
            const to = eye + DIAG[i];
            if (IN_BOARD[to] === 0 || ((from ^ to) & 0x80) !== 0) continue;
            const target = b[to];
            if (capturesOnly ? (target & opp) !== 0 : (target & self) === 0) out[n++] = from | (to << 8);
          }
          break;
        case HORSE:
          for (let i = 0; i < 4; i++) {
            if (b[from + ORTHO[i]] !== 0) continue;                   // off-board legs are empty, their jumps are off-board too
            for (let j = 0; j < 2; j++) {
              const to = from + HORSE_JUMP[2 * i + j];
              if (IN_BOARD[to] === 0) continue;
              const target = b[to];
              if (capturesOnly ? (target & opp) !== 0 : (target & self) === 0) out[n++] = from | (to << 8);
            }
          }
          break;
        case ROOK:
          for (let i = 0; i < 4; i++) {
            const d = ORTHO[i];
            let to = from + d;
            while (IN_BOARD[to] !== 0) {
              const target = b[to];
              if (target !== 0) {
                if ((target & opp) !== 0) out[n++] = from | (to << 8);
                break;
              }
              if (!capturesOnly) out[n++] = from | (to << 8);
              to += d;
            }
          }
          break;
        case CANNON:
          for (let i = 0; i < 4; i++) {
            const d = ORTHO[i];
            let to = from + d;
            while (IN_BOARD[to] !== 0 && b[to] === 0) {
              if (!capturesOnly) out[n++] = from | (to << 8);
              to += d;
            }
            if (IN_BOARD[to] === 0) continue;                         // no screen on this ray
            to += d;
            while (IN_BOARD[to] !== 0 && b[to] === 0) to += d;
            if (IN_BOARD[to] !== 0 && (b[to] & opp) !== 0) out[n++] = from | (to << 8);
          }
          break;
        default: {                                                    // PAWN
          const forward = side === RED ? from - 16 : from + 16;
          if (IN_BOARD[forward] !== 0) {
            const target = b[forward];
            if (capturesOnly ? (target & opp) !== 0 : (target & self) === 0) out[n++] = from | (forward << 8);
          }
          if (side === RED ? from < 0x80 : from >= 0x80) {            // across the river: one step sideways as well
            for (let d = -1; d <= 1; d += 2) {
              const to = from + d;
              if (IN_BOARD[to] === 0) continue;
              const target = b[to];
              if (capturesOnly ? (target & opp) !== 0 : (target & self) === 0) out[n++] = from | (to << 8);
            }
          }
        }
      }
    }
    return n;
  }

  /**
   * Play a pseudo-legal move of the side to move.
   * @param {number} mv
   * @returns {boolean} false (and nothing changed) when the move leaves the mover's king attacked
   */
  make(mv) {
    const from = mv & 255, to = (mv >> 8) & 255;
    const b = this.squares;
    const pc = b[from], captured = b[to];
    const side = this.side, other = side ^ 1;
    const keyBefore = this.key;
    const capturedSlot = this.slotOf[to];
    if (captured !== 0) this.delPiece(to, captured);
    this.movePiece(from, to, pc);
    if (this.attacked(this.kingSq[side], other)) {
      this.movePiece(to, from, pc);
      if (captured !== 0) this.putBack(to, captured, capturedSlot);
      return false;
    }
    const top = this.top;
    this.slList[top] = capturedSlot;
    this.mvList[top] = mv;
    this.pcList[top] = captured;
    this.keyList[top] = keyBefore;
    this.repFilter[keyBefore & (REP_FILTER_SIZE - 1)]++;
    this.side = other;
    this.key ^= Z_SIDE_KEY;
    this.lock ^= Z_SIDE_LOCK;
    this.chkList[top] = this.attacked(this.kingSq[other], side) ? 1 : 0;
    this.top = top + 1;
    return true;
  }

  /** Take back the last move made with make(). @returns {void} */
  unmake() {
    const top = this.top - 1;
    this.top = top;
    const mv = this.mvList[top], captured = this.pcList[top];
    this.repFilter[this.keyList[top] & (REP_FILTER_SIZE - 1)]--;
    this.side ^= 1;
    this.key ^= Z_SIDE_KEY;
    this.lock ^= Z_SIDE_LOCK;
    const from = mv & 255, to = mv >> 8;
    this.movePiece(to, from, this.squares[to]);
    if (captured !== 0) this.putBack(to, captured, this.slList[top]);
  }

  /** Pass: flip the side only. The 0 move it pushes also stops repetition scans. @returns {void} */
  makeNull() {
    const top = this.top;
    this.mvList[top] = 0;
    this.pcList[top] = 0;
    this.keyList[top] = this.key;
    this.repFilter[this.key & (REP_FILTER_SIZE - 1)]++;
    this.chkList[top] = 0;
    this.top = top + 1;
    this.changeSide();
  }

  /** @returns {void} */
  unmakeNull() {
    const top = this.top - 1;
    this.top = top;
    this.repFilter[this.keyList[top] & (REP_FILTER_SIZE - 1)]--;
    this.changeSide();
  }

  /** @returns {number[]} the legal moves of the side to move (make / unmake filter) */
  legalMoves() {
    const buf = new Int32Array(128);
    const n = this.generate(buf, false);
    /** @type {number[]} */
    const out = [];
    for (let i = 0; i < n; i++) {
      if (this.make(buf[i])) {
        this.unmake();
        out.push(buf[i]);
      }
    }
    return out;
  }

  /** @param {number} mv @returns {boolean} pseudo-legal for the side to move and survives make */
  isLegal(mv) {
    const buf = new Int32Array(128);
    const n = this.generate(buf, false);
    for (let i = 0; i < n; i++) {
      if (buf[i] !== mv) continue;
      if (!this.make(mv)) return false;
      this.unmake();
      return true;
    }
    return false;
  }

  /** @returns {boolean} the side to move is in check */
  inCheck() {
    const top = this.top;
    if (top > 0) return this.chkList[top - 1] !== 0;
    return this.attacked(this.kingSq[this.side], this.side ^ 1);
  }

  /**
   * Could a `bySide` piece capture a piece standing on `sq`? Fast version for king squares (A2.2): pawns, horses, rooks,
   * cannons and the `bySide` king on a file ray (facing kings). Advisors and elephants are skipped; use attackers() for other squares.
   * @param {number} sq
   * @param {number} bySide
   * @returns {boolean}
   */
  attacked(sq, bySide) {
    const b = this.squares;
    const tag = 8 << bySide;
    const pawn = tag + PAWN;
    // A pawn one step behind sq (seen from its own side), or beside sq when that pawn has crossed the river.
    // The pawn beside sq stands on sq's row, so "has crossed" is a test on sq.
    if (bySide === RED) {
      if (b[sq + 16] === pawn) return true;
      if (sq < 0x80 && (b[sq - 1] === pawn || b[sq + 1] === pawn)) return true;
    } else {
      if (b[sq - 16] === pawn) return true;
      if (sq >= 0x80 && (b[sq - 1] === pawn || b[sq + 1] === pawn)) return true;
    }
    const horse = tag + HORSE;
    if (b[sq - 17] === 0 && (b[sq - 33] === horse || b[sq - 18] === horse)) return true;
    if (b[sq - 15] === 0 && (b[sq - 31] === horse || b[sq - 14] === horse)) return true;
    if (b[sq + 15] === 0 && (b[sq + 14] === horse || b[sq + 31] === horse)) return true;
    if (b[sq + 17] === 0 && (b[sq + 18] === horse || b[sq + 33] === horse)) return true;
    const rook = tag + ROOK, cannon = tag + CANNON, king = tag + KING;
    for (let i = 0; i < 4; i++) {
      const d = ORTHO[i];
      let s = sq + d;
      while (IN_BOARD[s] !== 0 && b[s] === 0) s += d;
      if (IN_BOARD[s] === 0) continue;
      const first = b[s];
      if (first === rook || (first === king && (d === 16 || d === -16))) return true;
      s += d;
      while (IN_BOARD[s] !== 0 && b[s] === 0) s += d;
      if (b[s] === cannon) return true;
    }
    return false;
  }

  /**
   * Squares of all `bySide` pieces that pseudo-attack `sq` (A2.4): everything in attacked() plus advisors, elephants,
   * the adjacent king, and the flying general only when `sq` holds the other side's king.
   * @param {number} sq
   * @param {number} bySide
   * @returns {number[]}
   */
  attackers(sq, bySide) {
    const b = this.squares;
    const tag = 8 << bySide;
    /** @type {number[]} */
    const out = [];
    const pawn = tag + PAWN;
    const behind = bySide === RED ? sq + 16 : sq - 16;
    if (b[behind] === pawn) out.push(behind);
    if (bySide === RED ? sq < 0x80 : sq >= 0x80) {
      if (b[sq - 1] === pawn) out.push(sq - 1);
      if (b[sq + 1] === pawn) out.push(sq + 1);
    }
    const horse = tag + HORSE;
    for (let i = 0; i < 4; i++) {
      if (b[sq + DIAG[i]] !== 0) continue;
      for (let j = 0; j < 2; j++) {
        const s = sq + HORSE_FROM[2 * i + j];
        if (b[s] === horse) out.push(s);
      }
    }
    const rook = tag + ROOK, cannon = tag + CANNON, king = tag + KING;
    const holdsOtherKing = b[sq] === (24 - tag) + KING;
    for (let i = 0; i < 4; i++) {
      const d = ORTHO[i];
      let s = sq + d;
      while (IN_BOARD[s] !== 0 && b[s] === 0) s += d;
      if (IN_BOARD[s] === 0) continue;
      const first = b[s];
      if (first === rook) out.push(s);
      else if (first === king) {
        if (s === sq + d) {
          if (IN_FORT[sq] !== 0) out.push(s);                           // the adjacent king, inside its palace
        } else if (holdsOtherKing && (d === 16 || d === -16)) out.push(s);   // the flying general
      }
      s += d;
      while (IN_BOARD[s] !== 0 && b[s] === 0) s += d;
      if (b[s] === cannon) out.push(s);
    }
    if (IN_FORT[sq] !== 0) {
      const advisor = tag + ADVISOR;
      for (let i = 0; i < 4; i++) {
        const s = sq + DIAG[i];
        if (IN_FORT[s] !== 0 && b[s] === advisor) out.push(s);
      }
    }
    const elephant = tag + ELEPHANT;
    for (let i = 0; i < 4; i++) {
      const eye = sq + DIAG[i], s = eye + DIAG[i];
      if (b[s] === elephant && b[eye] === 0 && ((s ^ sq) & 0x80) === 0) out.push(s);
    }
    return out;
  }

  /**
   * Static exchange evaluation (A2.4): the value for the mover of playing mv and then the best capture sequence on mv's
   * destination. Uses real make / unmake, so cannon screens, horse legs, pins and the flying general are exact.
   * @param {number} mv a pseudo-legal move of the side to move
   * @returns {number} cp for the mover (-Infinity for an illegal move)
   */
  see(mv) {
    const from = mv & 255, to = (mv >> 8) & 255;
    const b = this.squares;
    const self = 8 << this.side;
    if ((b[from] & self) === 0 || (b[to] & self) !== 0) return -Infinity;
    const target = b[to];
    const gain = target !== 0 ? materialOf(target, to) : 0;
    if (!this.make(mv)) return -Infinity;
    const loss = bestCapture(this, to);
    this.unmake();
    return gain - loss;
  }

  /** @returns {number} cp for the side to move: vl[side] - vl[other] + guard(side) - guard(other) + 3 (A2.3) */
  evaluate() {
    const side = this.side, other = side ^ 1;
    const mine = this.count[side], theirs = this.count[other];
    // guard(s) = -4 * missing(s) * pressure(s): missing advisors and elephants of s, weighted by the other side's attackers
    const guardMine = -4 * (4 - mine[ADVISOR] - mine[ELEPHANT]) * (2 * theirs[ROOK] + theirs[CANNON] + theirs[HORSE]);
    const guardTheirs = -4 * (4 - theirs[ADVISOR] - theirs[ELEPHANT]) * (2 * mine[ROOK] + mine[CANNON] + mine[HORSE]);
    return this.vl[side] - this.vl[other] + guardMine - guardTheirs + 3;
  }

  /**
   * Repetition status of the current position along the reversible tail of the undo stacks (A2.5).
   * @returns {0|1|3|5|7} 0 = no repetition; 1 repetition, +2 the side to move checked on every move of the cycle, +4 the opponent did
   */
  repStatus() {
    const key = this.key;
    if (this.repFilter[key & (REP_FILTER_SIZE - 1)] === 0) return 0;
    const mvList = this.mvList, pcList = this.pcList, keyList = this.keyList, chkList = this.chkList;
    let own = false, selfChecks = 1, otherChecks = 1;
    for (let i = this.top - 1; i >= 0 && mvList[i] !== 0 && pcList[i] === 0; i--) {
      if (own) {
        selfChecks &= chkList[i];
        if (keyList[i] === key) {
          this.repAt = i;
          return /** @type {0|1|3|5|7} */ (1 + (selfChecks << 1) + (otherChecks << 2));
        }
      } else {
        otherChecks &= chkList[i];
      }
      own = !own;
    }
    return 0;
  }

  /** @param {number} mv @returns {MoveRef} */
  toRef(mv) {
    const from = mv & 255, to = (mv >> 8) & 255;
    return { from: { row: rowOf(from), col: colOf(from) }, to: { row: rowOf(to), col: colOf(to) } };
  }

  /** @param {MoveRef} ref @returns {number} */
  fromRef(ref) {
    return mkMove(sqOf(ref.from.row, ref.from.col), sqOf(ref.to.row, ref.to.col));
  }

  // ---- internal helpers (A2.1): they keep key, lock, vl, count and kingSq in step with `squares` ----

  /** Internal. @param {number} sq @param {number} pc @returns {void} */
  addPiece(sq, pc) {
    this.squares[sq] = pc;
    const side = pc >> 4;
    this.vl[side] += PST[(pc << 8) | sq];
    this.count[side][pc & 7]++;
    const z = Z_BASE[pc] | sq;
    this.key ^= Z_KEY[z];
    this.lock ^= Z_LOCK[z];
    if ((pc & 7) === KING) this.kingSq[side] = sq;
    const slot = side * PIECE_SLOTS + this.pieceN[side]++;
    this.pieceSq[slot] = sq;
    this.slotOf[sq] = slot;
  }

  /** Internal. @param {number} sq @param {number} pc @returns {void} */
  delPiece(sq, pc) {
    this.squares[sq] = 0;
    const side = pc >> 4;
    this.vl[side] -= PST[(pc << 8) | sq];
    this.count[side][pc & 7]--;
    const z = Z_BASE[pc] | sq;
    this.key ^= Z_KEY[z];
    this.lock ^= Z_LOCK[z];
    // The last piece of the list takes the freed slot.
    const slot = this.slotOf[sq];
    const last = side * PIECE_SLOTS + --this.pieceN[side];
    const moved = this.pieceSq[last];
    this.pieceSq[slot] = moved;
    this.slotOf[moved] = slot;
  }

  /**
   * Internal: addPiece for a piece that delPiece removed from `slot`, restoring the piece list exactly as it was.
   * @param {number} sq @param {number} pc @param {number} slot @returns {void}
   */
  putBack(sq, pc, slot) {
    this.addPiece(sq, pc);
    const last = this.slotOf[sq];
    if (slot === last) return;
    const other = this.pieceSq[slot];
    this.pieceSq[last] = other;
    this.slotOf[other] = last;
    this.pieceSq[slot] = sq;
    this.slotOf[sq] = slot;
  }

  /** Internal: delPiece(from) + addPiece(to) of the same piece (the counts do not change). @param {number} from @param {number} to @param {number} pc @returns {void} */
  movePiece(from, to, pc) {
    const b = this.squares;
    b[from] = 0;
    b[to] = pc;
    const side = pc >> 4;
    const base = pc << 8;
    this.vl[side] += PST[base | to] - PST[base | from];
    const z = Z_BASE[pc];
    this.key ^= Z_KEY[z | from] ^ Z_KEY[z | to];
    this.lock ^= Z_LOCK[z | from] ^ Z_LOCK[z | to];
    if ((pc & 7) === KING) this.kingSq[side] = to;
    const slot = this.slotOf[from];
    this.pieceSq[slot] = to;
    this.slotOf[to] = slot;
  }

  /** Internal: flip the side to move. @returns {void} */
  changeSide() {
    this.side ^= 1;
    this.key ^= Z_SIDE_KEY;
    this.lock ^= Z_SIDE_LOCK;
  }
}

/**
 * The best the side to move can win by capturing on `target`, or 0 when it declines (A2.4). Only the least valuable legal
 * attacker is tried.
 * @param {Position} pos
 * @param {number} target
 * @returns {number} >= 0
 */
function bestCapture(pos, target) {
  const b = pos.squares;
  const list = pos.attackers(target, pos.side);
  if (list.length > 1) list.sort((x, y) => materialOf(b[x], x) - materialOf(b[y], y));
  const victim = materialOf(b[target], target);
  for (const from of list) {
    if (!pos.make(mkMove(from, target))) continue;                      // illegal: pinned, or would leave the king attacked
    const v = victim - bestCapture(pos, target);
    pos.unmake();
    return v > 0 ? v : 0;
  }
  return 0;
}
